#!/usr/bin/env python3
"""
Data cleaning and processing pipeline
"""

import re
import json
import hashlib
from pathlib import Path
from datetime import datetime

class DataCleaner:
    def __init__(self):
        self.cleaning_levels = {
            'minimal': self._clean_minimal,
            'standard': self._clean_standard,
            'aggressive': self._clean_aggressive
        }
        
    def _clean_minimal(self, text):
        """Minimal cleaning - preserve most content"""
        # Just normalize line endings and encoding
        text = text.replace('\r\n', '\n')
        text = text.replace('\r', '\n')
        return text.strip()
    
    def _clean_standard(self, text):
        """Standard cleaning - remove obvious junk"""
        # Remove excessive whitespace
        text = re.sub(r'\n{4,}', '\n\n\n', text)
        text = re.sub(r' {2,}', ' ', text)
        
        # Remove common headers/footers
        patterns = [
            r'Copyright.*?(?:\n|$)',
            r'All rights reserved.*?(?:\n|$)',
            r'Generated by.*?(?:\n|$)'
        ]
        for pattern in patterns:
            text = re.sub(pattern, '', text, flags=re.IGNORECASE)
        
        return text.strip()
    
    def _clean_aggressive(self, text):
        """Aggressive cleaning - maximum compression"""
        text = self._clean_standard(text)
        
        # Remove all comments
        text = re.sub(r'#.*?$', '', text, flags=re.MULTILINE)
        text = re.sub(r'//.*?$', '', text, flags=re.MULTILINE)
        text = re.sub(r'/\*.*?\*/', '', text, flags=re.DOTALL)
        
        # Compress whitespace aggressively
        text = re.sub(r'\s+', ' ', text)
        
        return text.strip()
    
    def clean(self, text, level='standard'):
        """Clean text at specified level"""
        if level not in self.cleaning_levels:
            level = 'standard'
        return self.cleaning_levels[level](text)

class QualityScorer:
    def __init__(self):
        self.min_length = 100
        self.max_length = 1000000
        
    def score(self, text):
        """Score text quality 0-100"""
        score = 100
        
        # Length check
        if len(text) < self.min_length:
            return 0
        if len(text) > self.max_length:
            score -= 20
        
        # Diversity check
        unique_words = len(set(text.split()))
        total_words = len(text.split())
        if total_words > 0:
            diversity = unique_words / total_words
            if diversity < 0.1:
                score -= 30
        
        # Information density
        alphanum = sum(c.isalnum() for c in text)
        if len(text) > 0:
            density = alphanum / len(text)
            if density < 0.5:
                score -= 20
        
        return max(0, score)

class Categorizer:
    def __init__(self, config_path='configs/categories.yaml'):
        import yaml
        with open(config_path) as f:
            self.config = yaml.safe_load(f)
        self.categories = self.config['categories']
    
    def categorize(self, text, filepath=""):
        """Categorize content"""
        text_lower = text.lower()
        path_lower = str(filepath).lower()
        
        scores = {}
        for category, info in self.categories.items():
            score = 0
            for keyword in info['keywords']:
                if keyword in text_lower:
                    score += 10
                if keyword in path_lower:
                    score += 5
            scores[category] = score
        
        # Return top category
        if scores:
            return max(scores, key=scores.get)
        return 'uncategorized'

class ProcessingPipeline:
    def __init__(self):
        self.cleaner = DataCleaner()
        self.scorer = QualityScorer()
        self.categorizer = Categorizer()
        self.processed_dir = Path('data/processed')
        self.stats = {
            'processed': 0,
            'accepted': 0,
            'rejected': 0
        }
    
    def process_file(self, filepath, content):
        """Process single file through pipeline"""
        # Clean
        cleaned = self.cleaner.clean(content, level='standard')
        
        # Score
        score = self.scorer.score(cleaned)
        if score < 50:
            self.stats['rejected'] += 1
            return None
        
        # Categorize
        category = self.categorizer.categorize(cleaned, filepath)
        
        # Save
        output_dir = self.processed_dir / category
        output_dir.mkdir(parents=True, exist_ok=True)
        
        # Generate unique filename
        file_hash = hashlib.md5(str(filepath).encode()).hexdigest()[:8]
        output_file = output_dir / f"{Path(filepath).stem}_{file_hash}.txt"
        
        with open(output_file, 'w') as f:
            f.write(cleaned)
        
        self.stats['accepted'] += 1
        self.stats['processed'] += 1
        
        return {
            'original': filepath,
            'processed': output_file,
            'category': category,
            'score': score,
            'size': len(cleaned)
        }

if __name__ == "__main__":
    pipeline = ProcessingPipeline()
    print("Processing pipeline ready")